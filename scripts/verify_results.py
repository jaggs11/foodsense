"""Check every file in ``results/`` against its recorded manifest.

The reason this exists: `make eval` rewrites every evaluated number in the
project, and a regeneration that silently changes one is indistinguishable, in a
git diff full of timestamps, from one that changed nothing. This turns that into
a decision someone has to make on purpose.

Every difference is classified into exactly one of three outcomes:

``IDENTICAL``
    Byte-for-byte, or byte-for-byte once generation timestamps and wall-clock
    measurements are set aside. The latter are not results -- they are facts
    about the machine that ran them -- and holding them against the manifest
    would make every honest re-run look like a regression.
``EXPECTED``
    Differs only in fields listed as volatile, and the *substantive* content
    matches. Reported, not failed.
``UNEXPECTED``
    A real number moved. This exits non-zero and is meant to stop a release.

    python scripts/verify_results.py
    python scripts/verify_results.py --update    # after accepting a change
"""

from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
MANIFEST = RESULTS / "MANIFEST.sha256"

#: Lines that legitimately differ between two runs of the same experiment on the
#: same code. A generation stamp is not a result; neither is how many
#: milliseconds a laptop took. Everything else is.
VOLATILE = (
    re.compile(r"Generated by .* at \d{4}-\d{2}-\d{2}T"),
    re.compile(r"^\s*\"?(runtime_s|runtime_mean_s|total_runtime_s)\"?\s*[:=]", re.I),
)

#: Columns in a CSV whose values are wall-clock and therefore not comparable.
VOLATILE_COLUMNS = {"runtime_s", "runtime_mean_s", "total_runtime_s"}


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _canonical(path: Path) -> str | None:
    """The file's content with volatile parts removed, or None if unreadable."""
    try:
        text = path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return None  # binary (a figure): only the byte digest is meaningful

    if path.suffix == ".csv":
        lines = text.splitlines()
        if not lines:
            return text
        header = lines[0].split(",")
        drop = {i for i, name in enumerate(header) if name.strip() in VOLATILE_COLUMNS}
        if drop:
            return "\n".join(
                ",".join(v for i, v in enumerate(row.split(",")) if i not in drop) for row in lines
            )
        return text

    return "\n".join(
        line for line in text.splitlines() if not any(p.search(line) for p in VOLATILE)
    )


def _read_manifest() -> dict[str, str]:
    if not MANIFEST.exists():
        sys.exit(f"No manifest at {MANIFEST}. Create one with --update.")
    entries: dict[str, str] = {}
    for line in MANIFEST.read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        digest, _, name = line.partition("  ")
        entries[name.strip()] = digest.strip()
    return entries


def _current_files() -> list[Path]:
    return sorted(p for p in RESULTS.rglob("*") if p.is_file() and p.name != MANIFEST.name)


def _write_manifest(files: list[Path]) -> None:
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "HEAD"], capture_output=True, text=True, cwd=ROOT
        ).stdout.strip()
    except OSError:  # pragma: no cover - git absent
        commit = "unknown"
    lines = [
        "# results/ artefact manifest",
        f"# commit: {commit}",
        "#",
        "# Every evaluated number this project reports lives in one of these files.",
        "# `make eval` regenerates them; `make verify-results` diffs against this",
        "# manifest so a silent clobber becomes a visible one. Regenerate this file",
        "# ONLY when a change has been classified and deliberately accepted.",
        "#",
    ]
    for path in files:
        lines.append(f"{_digest(path)}  {path.relative_to(ROOT).as_posix()}")
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--update",
        action="store_true",
        help="rewrite the manifest to the current state (only after accepting the change)",
    )
    parser.add_argument(
        "--baseline",
        default="",
        help="git ref to compare canonical content against, e.g. phase-4.5",
    )
    args = parser.parse_args(argv)

    files = _current_files()
    if args.update:
        _write_manifest(files)
        print(f"manifest updated: {len(files)} files")
        return 0

    recorded = _read_manifest()
    present = {p.relative_to(ROOT).as_posix(): p for p in files}

    identical: list[str] = []
    expected: list[str] = []
    unexpected: list[str] = []

    for name in sorted(set(recorded) | set(present)):
        if name not in present:
            unexpected.append(f"{name}: MISSING (was in the manifest)")
            continue
        if name not in recorded:
            unexpected.append(f"{name}: NEW (not in the manifest)")
            continue

        path = present[name]
        if _digest(path) == recorded[name]:
            identical.append(name)
            continue

        # Bytes differ. Is it only the volatile parts? That needs the baseline
        # content, which the manifest does not carry -- only its hash -- so this
        # falls back to git when a ref is available.
        if args.baseline:
            try:
                blob = subprocess.run(
                    ["git", "show", f"{args.baseline}:{name}"],
                    capture_output=True,
                    cwd=ROOT,
                    check=True,
                ).stdout
            except (subprocess.CalledProcessError, OSError):
                unexpected.append(f"{name}: CHANGED (no baseline copy to compare against)")
                continue
            old = ROOT / ".verify_tmp"
            old.write_bytes(blob)
            same = _canonical(old) == _canonical(path)
            old.unlink()
            if same:
                expected.append(f"{name}: timestamps/runtimes only")
                continue
        unexpected.append(f"{name}: CHANGED (substantive content differs)")

    print(f"IDENTICAL  {len(identical)}")
    for name in identical:
        print(f"  = {name}")
    if expected:
        print(f"\nEXPECTED   {len(expected)}")
        for line in expected:
            print(f"  ~ {line}")
    if unexpected:
        print(f"\nUNEXPECTED {len(unexpected)}")
        for line in unexpected:
            print(f"  ! {line}")
        print(
            "\nA real number moved. Classify it before shipping; do not re-run hoping it settles."
        )
        return 1
    print("\nNothing substantive moved.")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
